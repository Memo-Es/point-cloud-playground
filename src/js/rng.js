/* Deterministic xorshift PRNG. Shared so that the scene painter and the point
   sampler can be driven from the same seed and agree on where things are. */
export function rng(seed = 1) {
  let s = seed >>> 0 || 1;
  return () => {
    s ^= s << 13; s >>>= 0;
    s ^= s >> 17;
    s ^= s << 5;  s >>>= 0;
    return s / 4294967296;
  };
}
